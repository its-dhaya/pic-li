// ─── Template: TypeScript ─────────────────────────────────────────────────────

function scaffoldTypescript(targetDir, name) {
  const src = (...p) => path.join(targetDir, "src", ...p);

  fs.ensureDirSync(src("components"));
  fs.ensureDirSync(src("screens"));
  fs.ensureDirSync(src("hooks"));
  fs.ensureDirSync(src("services"));
  fs.ensureDirSync(src("types"));
  fs.ensureDirSync(src("utils"));

  fs.writeFileSync(src("screens", "HomeScreen.tsx"), tsHomeScreen(name));
  fs.writeFileSync(src("types", "navigation.ts"), tsNavigationTypes());
}

function tsHomeScreen(name) {
  return `import React from 'react';
import { StyleSheet, Text, View } from 'react-native';
import type { NativeStackScreenProps } from '@react-navigation/native-stack';
import type { RootStackParamList } from '../types/navigation';

type Props = NativeStackScreenProps<RootStackParamList, 'Home'>;

export default function HomeScreen({ navigation }: Props) {
  return (
    <View style={styles.container}>
      <Text style={styles.title}>${name}</Text>
      <Text style={styles.subtitle}>Generated by PIC-LI</Text>
    </View>
  );
}

const styles = StyleSheet.create({
  container: { flex: 1, alignItems: 'center', justifyContent: 'center', backgroundColor: '#fff' },
  title:     { fontSize: 28, fontWeight: '700', marginBottom: 8 },
  subtitle:  { fontSize: 16, color: '#666' },
});
`;
}

function tsNavigationTypes() {
  return `export type RootStackParamList = {
  Home:    undefined;
  Profile: { userId: string };
  Settings: undefined;
};
`;
}

