"use strict";

const fs = require("fs-extra");
const path = require("path");
const { runSilent } = require("../../core/runCommand");

async function generate({ name, template, targetDir, onStep }) {
  const parentDir = path.dirname(targetDir);

  const expoTemplates = {
    default: "blank",
    tabs: "tabs",
    "with-typescript": "blank-typescript",
  };
  const expoTpl = expoTemplates[template] || "blank";

  onStep("Scaffolding Expo project");
  runSilent(
    `npx --yes create-expo-app@latest "${name}" --template ${expoTpl}`,
    { cwd: parentDir }
  );

  if (!fs.existsSync(targetDir)) {
    throw new Error(`Expo scaffold did not create directory: ${targetDir}`);
  }

  onStep("Organising folder structure");

  if (template === "tabs") {
    scaffoldTabs(targetDir, name);
  } else if (template === "with-typescript") {
    scaffoldTypescript(targetDir, name);
  } else {
    scaffoldDefault(targetDir, name);
  }

  onStep("Initializing Git");
  try {
    runSilent("git init", { cwd: targetDir });
  } catch {}
  const gi = `node_modules/\n.expo/\ndist/\n.env\n.DS_Store\n*.jks\n*.p8\n*.p12\n*.key\n*.mobileprovision\n`;
  fs.writeFileSync(path.join(targetDir, ".gitignore"), gi);

  onStep("Writing README");
  fs.writeFileSync(path.join(targetDir, "README.md"), readme(name, template));
}

// ─── Template: Default ────────────────────────────────────────────────────────

function scaffoldDefault(targetDir, name) {
  const src = (...p) => path.join(targetDir, "src", ...p);

  fs.ensureDirSync(src("screens"));
  fs.ensureDirSync(src("components"));
  fs.ensureDirSync(src("hooks"));
  fs.ensureDirSync(src("services"));
  fs.ensureDirSync(src("utils"));

  fs.writeFileSync(src("screens", "HomeScreen.js"), defaultHomeScreen(name));
}

function defaultHomeScreen(name) {
  return `import { StyleSheet, Text, View } from 'react-native';

export default function HomeScreen() {
  return (
    <View style={styles.container}>
      <Text style={styles.title}>${name}</Text>
      <Text style={styles.subtitle}>Generated by PIC-LI</Text>
    </View>
  );
}

const styles = StyleSheet.create({
  container: { flex: 1, alignItems: 'center', justifyContent: 'center', backgroundColor: '#fff' },
  title:     { fontSize: 28, fontWeight: '700', marginBottom: 8 },
  subtitle:  { fontSize: 16, color: '#666' },
});
`;
}

// ─── Template: Tabs ───────────────────────────────────────────────────────────

function scaffoldTabs(targetDir, name) {
  const src = (...p) => path.join(targetDir, "src", ...p);

  fs.ensureDirSync(src("navigation"));
  fs.ensureDirSync(src("screens"));
  fs.ensureDirSync(src("components"));
  fs.ensureDirSync(src("hooks"));

  fs.writeFileSync(src("screens", "HomeScreen.js"), tabHomeScreen(name));
  fs.writeFileSync(src("screens", "ProfileScreen.js"), tabProfileScreen());
  fs.writeFileSync(src("screens", "SettingsScreen.js"), tabSettingsScreen());
  fs.writeFileSync(src("navigation", "TabNavigator.js"), tabNavigator());
  fs.writeFileSync(src("navigation", "AppNavigator.js"), appNavigator());
}

